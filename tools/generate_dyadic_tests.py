#!/usr/bin/env python3
"""Generate tests/dyadic_generated_tests.cpp: static_asserts on aerobus::dyadic, numbers m 2^e with an odd bigint m.
Expected values come from Python's exact fractions.

Usage: tools/generate_dyadic_tests.py [--check]
  --check  compare with the file in the repository instead of writing it
"""
import math
import random
import sys
from fractions import Fraction
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "dyadic_generated_tests.cpp"
FORMATS = {"float": (24, -126, 127), "double": (53, -1022, 1023)}


def canonical(value):
    """value = m 2^e, m odd (or 0, 0)"""
    assert value.denominator & (value.denominator - 1) == 0
    if value == 0:
        return 0, 0
    m, e = value.numerator, -(value.denominator.bit_length() - 1)
    while m % 2 == 0:
        m //= 2
        e += 1
    return m, e


def bigint_type(m):
    magnitude, digits = abs(m), []
    while magnitude:
        digits.append(magnitude & 0xFFFFFFFF)
        magnitude >>= 32
    return "B<" + ("true" if m < 0 else "false") + "".join(f", 0x{d:x}U" for d in reversed(digits)) + ">"


def T(value):
    m, e = canonical(value)
    return f"D<{bigint_type(m)}, {e}>"


def round_exact(value, precision, emin, emax):
    """value >= 0 rounded to nearest, ties to even: (m, k), or None for an overflow"""
    if value == 0:
        return 0, 0
    exponent = value.numerator.bit_length() - value.denominator.bit_length()
    if Fraction(2) ** exponent > value:
        exponent -= 1
    k = max(exponent, emin) - precision + 1
    scaled = value / Fraction(2) ** k
    m = math.floor(scaled)
    rest = scaled - m
    if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and m % 2 == 1):
        m += 1
    if m * Fraction(2) ** k >= Fraction(2) ** (emax + 1):
        return None
    return m, k


def literal(value, type_name):
    rounded = round_exact(abs(value), *FORMATS[type_name])
    sign = "-" if value < 0 else ""
    if rounded is None:
        return f"{sign}std::numeric_limits<{type_name}>::infinity()"
    suffix = "F" if type_name == "float" else ""
    return f"{sign}0x{rounded[0]:x}p{rounded[1]:+d}{suffix}"


def main():
    rng = random.Random(2026)

    def rnd(bits=128, span=120):
        m = rng.getrandbits(rng.randint(1, bits)) | 1
        return Fraction(m if rng.random() < 0.5 else -m) * Fraction(2) ** rng.randint(-span, span)

    edges = [Fraction(0), Fraction(1), Fraction(-1), Fraction(1, 2), Fraction(-3, 4), Fraction(2**40), Fraction(5, 2**70)]
    pairs = [(a, b) for a in edges for b in edges] + [(rnd(), rnd()) for _ in range(25)]
    w = ["// Generated by tools/generate_dyadic_tests.py from Python's exact fractions; do not edit by hand.",
         "#include <gtest/gtest.h>\n#include <cstdint>\n#include <limits>\n#include <type_traits>\n\n#include \"aerobus.h\"\n",
         "namespace {\nusing aerobus::dyadic;\ntemplate<bool negative, uint32_t... digits>",
         "using B = aerobus::bigint::val<negative, digits...>;\ntemplate<typename M, int64_t e>",
         "using D = dyadic::val<M, e>;\n}  // namespace\n"]

    def case(op, a, b, r):
        return f"    static_assert(std::is_same_v<dyadic::{op}<{T(a)}, {T(b)}>, {T(r)}>);"

    w.append("TEST(dyadic_generated, add) {")
    w += [case("add_t", a, b, a + b) for a, b in pairs]
    w.append("}\n\nTEST(dyadic_generated, sub) {")
    w += [case("sub_t", a, b, a - b) for a, b in pairs]
    w.append("}\n\nTEST(dyadic_generated, mul) {")
    w += [case("mul_t", a, b, a * b) for a, b in pairs]
    w.append("}\n\nTEST(dyadic_generated, euclidean_division) {")
    for a, b in pairs:
        if b == 0:
            continue
        ma, ea = canonical(a)
        mb, eb = canonical(b)
        q = abs(ma) // abs(mb)
        q = q if (ma < 0) == (mb < 0) else -q
        quotient = Fraction(q) * Fraction(2) ** (ea - eb)
        w.append(case("div_t", a, b, quotient))
        w.append(case("mod_t", a, b, a - quotient * b))
    w.append("}\n\nTEST(dyadic_generated, gcd) {")
    for a, b in pairs:
        w.append(case("gcd_t", a, b, Fraction(math.gcd(canonical(a)[0], canonical(b)[0]))))
    w.append("}\n\nTEST(dyadic_generated, comparisons) {")
    for a, b in pairs:
        w.append(f"    static_assert(dyadic::gt_v<{T(a)}, {T(b)}> == {str(a > b).lower()} && "
                 f"dyadic::lt_v<{T(a)}, {T(b)}> == {str(a < b).lower()} && "
                 f"dyadic::eq_v<{T(a)}, {T(b)}> == {str(a == b).lower()});")
    w.append("}\n\nTEST(dyadic_generated, from_hex_float) {")
    hex_values = ["-0x1.55554cp-3", "0x1.110edap-7", "-0x1.9f70f2p-13", "0x1.5dc94p-19", "0x0p+0", "-0x0.0p+0", "0x1p-1074",
                  "0x1.fffffffffffffp+1023", "0x1.8p+0", "0x.8p1", "0xAbC.dEfp-4", "0x3p5"]
    for _ in range(20):
        hex_values.append(math.ldexp(rng.random() - 0.5, rng.randint(-200, 200)).hex())
    for h in hex_values:
        w.append(f'    static_assert(std::is_same_v<dyadic::from_hex_float_t<"{h}">, {T(Fraction(float.fromhex(h)))}>);')
    w.append("}\n\nTEST(dyadic_generated, correctly_rounded_conversions) {")
    conversions = [rnd(200, 400) for _ in range(30)]
    for precision, emin, emax in FORMATS.values():
        low = Fraction(2) ** (emin - precision + 1)
        one = Fraction(2) ** (precision - 1)
        largest = (2 - Fraction(2) ** (1 - precision)) * Fraction(2) ** emax
        conversions += [one * 2 + 1, one * 2 + 3, -(one * 2 + 1), low, low / 2, low * 3 / 2, -low / 2, low / 8,
                        Fraction(2) ** emin - low / 2, largest, largest + Fraction(2) ** (emax - precision),
                        Fraction(2) ** (emax + 1), Fraction(2) ** (emax + 200), low / 2**200]
    for type_name in FORMATS:
        for value in conversions:
            w.append(f"    static_assert({T(value)}::get<{type_name}>() == {literal(value, type_name)});")
    w.append("}")
    w = [line + "  // NOLINT(whitespace/line_length)" if len(line) > 120 and "\n" not in line else line for line in w]
    text = "\n".join(w) + "\n"
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text() != text:
            print(f"{OUTPUT} differs from the output of {Path(__file__).name}: regenerate it")
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
