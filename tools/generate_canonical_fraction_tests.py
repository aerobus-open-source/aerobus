#!/usr/bin/env python3
"""Generate tests/canonical_fraction_tests.cpp: every fraction of aerobus is in lowest terms, with a positive
denominator, whatever the way it is written, and hexadecimal literals give the exact value. Expected values come from
Python's exact fractions.

Usage: tools/generate_canonical_fraction_tests.py [--check]
  --check  compare with the file in the repository instead of writing it
"""
import random
import sys
from fractions import Fraction
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "canonical_fraction_tests.cpp"


def bigint_type(m):
    magnitude, digits = abs(m), []
    while magnitude:
        digits.append(magnitude & 0xFFFFFFFF)
        magnitude >>= 32
    return "B<" + ("true" if m < 0 else "false") + "".join(f", 0x{d:x}U" for d in reversed(digits)) + ">"


def main():
    rng = random.Random(2026)
    w = ["// Generated by tools/generate_canonical_fraction_tests.py from Python's exact fractions; do not edit by hand.",
         "#include <gtest/gtest.h>\n#include <cstdint>\n#include <type_traits>\n\n#include \"aerobus.h\"\n",
         "namespace {\ntemplate<bool negative, uint32_t... digits>\nusing B = aerobus::bigint::val<negative, digits...>;",
         "using QB = aerobus::FractionField<aerobus::bigint>;\nusing aerobus::i32;\nusing aerobus::i64;",
         "using aerobus::q32;\nusing aerobus::q64;\n}  // namespace\n"]

    def qb(n, d):
        return f"QB::val<{bigint_type(n)}, {bigint_type(d)}>"

    def impl(f):
        return f"QB::val_impl<{bigint_type(f.numerator)}, {bigint_type(f.denominator)}>"

    w.append("TEST(canonical_fractions, bigint) {")
    pairs = [(2, 4), (-2, 4), (2, -4), (-2, -4), (0, 7), (0, -7), (6, 3), (1, -1), (7, 1), (-7, 1)]
    for _ in range(30):
        g = rng.getrandbits(rng.randint(1, 128)) + 1
        n = rng.getrandbits(rng.randint(1, 128)) * g * rng.choice((1, -1))
        d = (rng.getrandbits(rng.randint(1, 128)) + 1) * g * rng.choice((1, -1))
        pairs.append((n, d))
    for n, d in pairs:
        w.append(f"    static_assert(std::is_same_v<{qb(n, d)}, {impl(Fraction(n, d))}>);")
    w.append("}\n\nTEST(canonical_fractions, native_integers) {")
    for n, d in [(2, 4), (-6, -9), (6, -9), (0, 5), (0, -5), (12, 4), (1000000, 3000000), (-1, 1)]:
        f = Fraction(n, d)
        w.append(f"    static_assert(std::is_same_v<q32::val<i32::val<{n}>, i32::val<{d}>>, "
                 f"q32::val_impl<i32::val<{f.numerator}>, i32::val<{f.denominator}>>>);")
        w.append(f"    static_assert(std::is_same_v<q64::val<i64::val<{n}>, i64::val<{d}>>, "
                 f"q64::val_impl<i64::val<{f.numerator}>, i64::val<{f.denominator}>>>);")
    w.append("}\n\nTEST(hex_float_literals, bigint) {")
    literals = ["0x1.8p-3", "-0x1.55554cp-3", "0x1.110edap-7", "-0x1.9f70f2p-13", "0x1.5dc94p-19", "0x0p+0", "-0x0.0p+0",
                "0x0p-5000", "0x1p-1074", "0x1.fffffffffffffp+1023", "0x1.23456789abcdfp-40", "0x.8p1", "0xAbC.dEfp-4",
                "0x3p5", "+0x1p0", "0X1P+1", "0x10p-4"]
    for _ in range(20):
        literals.append((rng.random() - 0.5).hex())
    for lit in literals:
        f = Fraction(float.fromhex(lit))
        w.append(f'    static_assert(std::is_same_v<aerobus::from_hex_float_t<"{lit}">, {impl(f)}>);')
    # beyond double: the literal is exact
    big = "0x1.123456789abcdef0123456789abcdef1p-200"
    f = (Fraction(int("1123456789abcdef0123456789abcdef1", 16)) / 16 ** 32) / 2 ** 200
    w.append(f'    static_assert(std::is_same_v<aerobus::from_hex_float_t<"{big}">, {impl(f)}>);')
    w.append("}\n\nTEST(hex_float_literals, round_trip_through_double) {")
    for _ in range(30):
        v = (rng.random() - 0.5) * 2.0 ** rng.randint(-300, 300)
        w.append(f'    static_assert(aerobus::from_hex_float_t<"{v.hex()}">::get<double>() == {v.hex()});')
    w.append("}\n\nTEST(hex_float_literals, native_integers) {")
    for lit in ["0x1.8p-3", "-0x1.1p+4", "0x1p-30", "0x3p+0", "0x0p+0", "-0x1.8p+1"]:
        f = Fraction(float.fromhex(lit))
        w.append(f'    static_assert(std::is_same_v<aerobus::from_hex_float_t<"{lit}", i64>, '
                 f"q64::val_impl<i64::val<{f.numerator}>, i64::val<{f.denominator}>>>);")
        w.append(f'    static_assert(std::is_same_v<aerobus::from_hex_float_t<"{lit}", i32>, '
                 f"q32::val_impl<i32::val<{f.numerator}>, i32::val<{f.denominator}>>>);")
    w.append("}")
    w = [line + "  // NOLINT(whitespace/line_length)" if len(line) > 120 and "\n" not in line else line for line in w]
    text = "\n".join(w) + "\n"
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text() != text:
            print(f"{OUTPUT} differs from the output of {Path(__file__).name}: regenerate it")
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
