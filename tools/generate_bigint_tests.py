#!/usr/bin/env python3
"""Generate tests/bigint_tests.cpp: static_asserts on aerobus::bigint, expected values from Python's integers.

The divisions in div_add_back take the rare add-back step of Knuth's algorithm D; they were found by a structured
search over digits such as 0x7fffffff, 0x80000000 and 0xffffffff.

Usage: tools/generate_bigint_tests.py [--check]
  --check  compare with the file in the repository instead of writing it
"""
import math
import random
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "bigint_tests.cpp"
random.seed(2026)
B = 1 << 32
def T(x):
    neg = x < 0; m = -x if neg else x
    d = []
    while m: d.append(m & (B - 1)); m >>= 32
    d = d[::-1]
    return "B<" + ("true" if neg else "false") + "".join(f", 0x{v:x}" for v in d) + ">"
def rnd(maxlimbs=6):
    n = random.randint(0, maxlimbs)
    x = random.getrandbits(32 * n) if n else 0
    if random.random() < 0.3 and n:  # long runs of ones, carry chains
        x = (1 << (32 * n)) - 1 - random.getrandbits(random.randint(0, 8))
    return -x if random.random() < 0.5 else x
def tdiv(a, b):
    q = abs(a) // abs(b); q = q if (a < 0) == (b < 0) else -q
    return q, a - q * b
edges = [0, 1, -1, B - 1, B, -B, B * B - 1, -(B * B - 1), (1 << 192) - 1]
out = []
w = out.append
w('// Generated by tools/generate_bigint_tests.py from Python\'s integers; do not edit by hand.')
w('#include <gtest/gtest.h>\n#include <cstdint>\n#include <string>\n#include <type_traits>\n\n#include "aerobus.h"\n')
w('namespace {\ntemplate<bool negative, uint32_t... digits>\nusing B = aerobus::bigint::val<negative, digits...>;\nusing aerobus::bigint;\n}  // namespace\n')
def case(op, a, b, r):
    return f"    static_assert(std::is_same_v<bigint::{op}<{T(a)}, {T(b)}>, {T(r)}>);"
pairs = [(a, b) for a in edges for b in edges] + [(rnd(), rnd()) for _ in range(25)]
w('TEST(bigint, add) {'); [w(case("add_t", a, b, a + b)) for a, b in pairs[::3] + pairs[-25:]]; w('}\n')
w('TEST(bigint, sub) {'); [w(case("sub_t", a, b, a - b)) for a, b in pairs[1::3] + pairs[-25:]]; w('}\n')
w('TEST(bigint, mul) {'); [w(case("mul_t", a, b, a * b)) for a, b in pairs[2::3] + pairs[-25:]]; w('}\n')
divs = [(a, b) for a, b in pairs if b != 0]
divs += [(rnd(8), rnd(3) or 7) for _ in range(25)]
addback = [(0x7fffffff000000000000000080000000, 0xfffffffe000000007fffffff),
           (0x8000000100000000fffffffefffffffe80000001, 0x8000000000000000fffffffe),
           (0xfffffffe800000018000000000000001fffffffe, 0xffffffff800000017fffffff)]
w('TEST(bigint, div_and_mod_truncate_like_cpp) {')
for a, b in divs:
    q, r = tdiv(a, b)
    w(case("div_t", a, b, q)); w(case("mod_t", a, b, r))
w('}\n')
w('// these divisions take the rare add-back step of Knuth\'s algorithm D')
w('TEST(bigint, div_add_back) {')
for a, b in addback:
    for sa, sb in ((1, 1), (-1, 1)):
        q, r = tdiv(sa * a, sb * b)
        w(case("div_t", sa * a, sb * b, q)); w(case("mod_t", sa * a, sb * b, r))
w('}\n')
big_a = random.getrandbits(32 * 40) | (1 << (32 * 40 - 1)); big_b = random.getrandbits(32 * 20) | (1 << (32 * 20 - 1))
q, r = tdiv(big_a, big_b)
w('// 40 digits by 20 digits of 32 bits')
w('TEST(bigint, div_large) {'); w(case("div_t", big_a, big_b, q)); w(case("mod_t", big_a, big_b, r)); w('}\n')
w('TEST(bigint, gcd) {')
for _ in range(12):
    g = abs(rnd(3)) or 1; a = g * rnd(3); b = g * rnd(3)
    w(case("gcd_t", a, b, math.gcd(a, b)))
w(case("gcd_t", 0, -5, 5)); w(case("gcd_t", 12, 0, 12))
w('}\n')
w('TEST(bigint, comparisons) {')
for a, b in pairs[:40]:
    w(f"    static_assert(bigint::gt_v<{T(a)}, {T(b)}> == {str(a > b).lower()} && bigint::lt_v<{T(a)}, {T(b)}> == {str(a < b).lower()} && bigint::eq_v<{T(a)}, {T(b)}> == {str(a == b).lower()});")
w('}\n')
w('TEST(bigint, construction) {')
for x in [0, 1, -1, 0x7fffffffffffffff, -0x8000000000000000, 1 << 32, 123456789]:
    w(f"    static_assert(std::is_same_v<bigint::inject_constant_t<{('INT64_MIN' if x == -0x8000000000000000 else str(x) + ('LL' if abs(x) > 2**31 else ''))}>, {T(x)}>);")
for x in [0, 0x12a, 0x123abf67ea, (1 << 128) - 1, random.getrandbits(200)]:
    w(f'    static_assert(std::is_same_v<bigint::from_hex_t<"{x:X}">, {T(x)}>);')
    w(f'    static_assert(std::is_same_v<bigint::from_string_t<"{x}">, {T(x)}>);')
w(f'    static_assert(std::is_same_v<bigint::from_string_t<"-{(1 << 100) + 7}">, {T(-((1 << 100) + 7))}>);')
w(f'    static_assert(std::is_same_v<bigint::from_hex_t<"-1F">, {T(-31)}>);')
w('}\n')
w('TEST(bigint, to_string) {')
for x in [0, -1, 1 << 100, -(3 ** 80)]:
    w(f'    EXPECT_EQ(({T(x)}::to_string()), "{x}");')
w(f'    EXPECT_EQ(({T((1 << 128) - 1)}::to_hex()), "0X{(1 << 128) - 1:X}");')
w(f'    EXPECT_EQ(({T(-255)}::to_hex()), "-0XFF");')
w('}\n')
w('TEST(bigint, get) {')
w(f'    static_assert({T(1 << 100)}::get<double>() == 0x1p100);')
w(f'    static_assert({T(-(B + 1))}::get<double>() == -4294967297.0);')
w(f'    static_assert({T(-12)}::get<int64_t>() == -12);')
w('}\n')
w('''TEST(bigint, is_an_euclidean_domain) {
    static_assert(aerobus::IsEuclideanDomain<bigint>);
    static_assert(!aerobus::IsField<bigint>);
    static_assert(bigint::zero::is_zero_v && !bigint::one::is_zero_v);
    static_assert(bigint::pos_v<bigint::one> && !bigint::pos_v<bigint::zero>);
}

TEST(bigint, coefficients_of_polynomials_and_fractions) {
    // (2^64 x + 1)^2 = 2^128 x^2 + 2^65 x + 1
    using PB = aerobus::polynomial<bigint>;
    using P = PB::val<B<false, 1, 0, 0>, bigint::one>;''')
w(f'    static_assert(std::is_same_v<PB::mul_t<P, P>, PB::val<{T(1 << 128)}, {T(1 << 65)}, bigint::one>>);')
w('''    // fractions of bigints: 1/3 + 1/6 = 1/2
    using QB = aerobus::FractionField<bigint>;
    using third = QB::val<bigint::one, bigint::inject_constant_t<3>>;
    using sixth = QB::val<bigint::one, bigint::inject_constant_t<6>>;
    static_assert(QB::eq_v<QB::add_t<third, sixth>, QB::val<bigint::one, bigint::inject_constant_t<2>>>);
    static_assert(QB::add_t<third, sixth>::get<double>() == 0.5);
}''')
out = [l + "  // NOLINT(whitespace/line_length)" if len(l) > 120 else l for l in out]
text = "\n".join(out) + "\n"
if "--check" in sys.argv[1:]:
    if OUTPUT.read_text() != text:
        print(f"{OUTPUT} differs from the output of {Path(__file__).name}: regenerate it")
        sys.exit(1)
    print(f"{OUTPUT.name} is up to date")
else:
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
